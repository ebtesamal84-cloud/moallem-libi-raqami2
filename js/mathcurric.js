  /* ==================== أدوات العرض ==================== */
  function totalLessons() {
    var n = 0, i;
    for (i = 0; i < UNITS.length; i++) n += UNITS[i].lessons.length;
    return n;
  }

  function oBullets(arr) {
    var out = '', i;
    for (i = 0; i < arr.length; i++) { if (i) out += '<br>• '; out += esc(arr[i]); }
    return out;
  }

  function stepsHtml(l) {
    var out = '<ol style="margin:4px 18px 0 0">', i;
    for (i = 0; i < l.s.length; i++) {
      out += '<li style="margin-bottom:3px"><b>' + esc(l.s[i][0]) + ':</b> ' + esc(l.s[i][1]) + '</li>';
    }
    return out + '</ol>';
  }

  function termHtml(u) {
    return u.term ? ' <span class="mini">(' + esc(u.term) + ')</span>' : '';
  }

  function lessonHtml(u, ui, l, li) {
    var id = 'm9-' + ui + '-' + li;
    return '<details id="' + id + '" style="margin:6px 0 8px;border:1px solid rgba(11,37,69,.14);border-radius:10px;padding:6px 10px;background:rgba(255,255,255,.5)">' +
      '<summary style="cursor:pointer;font-weight:700">📖 الدرس ' + (li + 1) + ': ' + esc(l.t) + '</summary>' +
      '<div style="margin-top:8px">' +
      '<p style="margin:2px 0"><b>🎯 الأهداف:</b><br>• ' + oBullets(l.o) + '</p>' +
      '<p style="margin:6px 0"><b>🎬 التمهيد والتهيئة:</b> ' + esc(l.w) + '</p>' +
      '<p style="margin:6px 0 0"><b>⏱️ خطوات التدريس (45 دقيقة):</b></p>' + stepsHtml(l) +
      '<p style="margin:6px 0"><b>⚠️ خطأ شائع وعلاجه:</b> ' + esc(l.e) + '</p>' +
      '<p style="margin:6px 0"><b>✅ التقويم:</b> ' + esc(l.c) + '</p>' +
      '<p style="margin:6px 0"><b>🏠 الواجب المنزلي:</b> ' + esc(l.h) + '</p>' +
      '<p style="margin:6px 0"><b>🧰 الوسائل والمواد:</b> ' + esc(l.m) + '</p>' +
      '<div class="btn-row" style="margin-top:8px">' +
      '<button type="button" class="btn btn-primary btn-sm" data-m9prep="' + ui + ',' + li + '">📝 تحضير من هذا الدرس</button>' +
      '<button type="button" class="btn btn-soft btn-sm" data-m9print="' + ui + ',' + li + '">🖨 طباعة دليل الدرس</button>' +
      '</div></div></details>';
  }

  function unitHtml(u, ui) {
    var out = '<div id="m9unit-' + ui + '" style="margin-top:16px">' +
      '<h4 style="margin:6px 0 4px;color:#0E7C86">' + esc(u.t) + termHtml(u) +
      ' <button type="button" class="btn btn-soft btn-sm" data-m9pu="' + ui + '" style="font-size:12px;vertical-align:middle">🖨 طباعة الوحدة</button></h4>' +
      '<p class="mini" style="margin:0 0 6px">' + esc(u.ov) + '</p>', i;
    for (i = 0; i < u.lessons.length; i++) out += lessonHtml(u, ui, u.lessons[i], i);
    return out + '</div>';
  }

  function chipsHtml() {
    var out = '<div class="btn-row" style="flex-wrap:wrap;margin:6px 0 2px">', i, s, p;
    for (i = 0; i < UNITS.length; i++) {
      s = UNITS[i].t.replace('الوحدة ', '');
      p = s.indexOf('('); if (p > 0) s = s.slice(0, p);
      out += '<button type="button" class="btn btn-navy btn-sm" data-m9go="' + i + '">' + (i + 1) + '. ' + esc(s) + '</button>';
    }
    return out + '</div>';
  }

  function headPairs(u, extra) {
    var a = [['المادة', SUBJECT], ['الصف', GRADE]];
    if (u.term) a.push(['الفصل', u.term]);
    if (u) a.push(['الوحدة', u.t]);
    if (extra) a.push(extra);
    return a;
  }

  /* ==================== الطباعة (A4) ==================== */
  function printLesson(ui, li) {
    var u = UNITS[ui], l = u.lessons[li], i, steps = [];
    for (i = 0; i < l.s.length; i++) steps.push(l.s[i][0] + ' — ' + l.s[i][1]);
    UI.print(
      UI.prHead(l.t, 'دليل معلم — المعلم الليبي الرقمي',
        headPairs(u, ['زمن الحصة', '45 دقيقة']))
      + UI.prSec('الأهداف', UI.prBullets(l.o))
      + UI.prSec('التمهيد والتهيئة', UI.prPara(l.w))
      + UI.prSec('خطوات التدريس', UI.prBullets(steps))
      + UI.prSec('خطأ شائع وعلاجه', UI.prPara(l.e))
      + UI.prSec('التقويم', UI.prPara(l.c))
      + UI.prSec('الواجب المنزلي', UI.prPara(l.h))
      + UI.prSec('الوسائل والمواد', UI.prPara(l.m))
      + '<p class="pr-s" style="margin-top:12px">ترتيب الدرس وفق فهرس كتاب الرياضيات الرسمي للصف التاسع — وكتاب الطالب ودليل المعلم مرجعكِ النصّي. أُنشئ بواسطة «المعلم الليبي الرقمي».</p>'
      + UI.prSign()
    );
  }

  function printUnit(ui) {
    var u = UNITS[ui], body = '', i, j, l, steps;
    for (i = 0; i < u.lessons.length; i++) {
      l = u.lessons[i]; steps = [];
      for (j = 0; j < l.s.length; j++) steps.push(l.s[j][0] + ' — ' + l.s[j][1]);
      body += UI.prSec('الدرس ' + (i + 1) + ': ' + l.t,
        UI.prBullets(l.o)
        + UI.prPara('<b>التمهيد:</b> ' + l.w)
        + UI.prPara('<b>الخطوات:</b> ' + steps.join(' · '))
        + UI.prPara('<b>الخطأ الشائع:</b> ' + l.e)
        + UI.prPara('<b>التقويم:</b> ' + l.c)
        + UI.prPara('<b>الواجب:</b> ' + l.h)
        + UI.prPara('<b>الوسائل:</b> ' + (l.m || '')));
    }
    UI.print(
      UI.prHead(u.t, 'دليل معلم — ' + TITLE, headPairs(u, ['عدد الدروس', u.lessons.length + ' دروس']))
      + body
      + '<p class="pr-s">مرجع الترتيب: فهرس الكتاب الرسمي — وكتاب الطالب ودليل المعلم مرجعكِ النصّي.</p>'
      + UI.prSign()
    );
  }

