  function open() {
    var html = '<div class="notice"><b>' + esc(TITLE) + '</b> — ' + totalLessons() +
      ' درسًا في ' + UNITS.length + ' وحدات.<br><span class="mini">' + esc(NOTE) + '</span></div>' +
      chipsHtml(), i;
    for (i = 0; i < UNITS.length; i++) html += unitHtml(UNITS[i], i);
    html += '<div class="btn-row" style="margin-top:14px">' +
      '<button type="button" class="btn btn-soft" id="m9Close">إغلاق</button></div>';

    UI.modal('📐 دليل معلم الرياضيات — الصف التاسع', html);

    $('#m9Close').onclick = UI.closeModal;
    $$('[data-m9go]').forEach(function (b) {
      b.onclick = function () {
        var el = document.getElementById('m9unit-' + b.getAttribute('data-m9go'));
        if (el && el.scrollIntoView) el.scrollIntoView({ block: 'start' });
      };
    });
    $$('[data-m9print]').forEach(function (b) {
      b.onclick = function () {
        var p = b.getAttribute('data-m9print').split(',');
        printLesson(+p[0], +p[1]);
      };
    });
    $$('[data-m9prep]').forEach(function (b) {
      b.onclick = function () {
        var p = b.getAttribute('data-m9prep').split(',');
        seedPrep(+p[0], +p[1]);
      };
    });
    $$('[data-m9pu]').forEach(function (b) {
      b.onclick = function () { printUnit(+b.getAttribute('data-m9pu')); };
    });
  }

